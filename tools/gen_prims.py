#!/usr/bin/env python3
"""Regenerates src/prim_digests.ml from official lean4export files.

usage: gen_prims.py --exe _build/default/tools/gen_prims/gen_prims.exe FILE...

Each file is checked with every primitive trusted (tools/gen_prims/gen_prims.ml), and the fingerprint of every primitive
the file defines is collected. The table keeps every distinct fingerprint seen for a name (one per toolchain). Review the
diff: a new digest is a new definition the kernel will accelerate.
"""

import argparse
import collections
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "src" / "prim_digests.ml"


def current():
    table = collections.OrderedDict()
    if TARGET.exists():
        for line in TARGET.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line.startswith('("'):
                name = line.split('"')[1]
                table[name] = {part for part in line.split('"')[3:] if len(part) == 64}
    return table


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exe", required=True)
    ap.add_argument("--timeout", type=int, default=3600)
    ap.add_argument("files", nargs="+")
    args = ap.parse_args()
    table = current()
    for f in args.files:
        try:
            p = subprocess.run(
                [args.exe, f],
                capture_output=True,
                text=True,
                timeout=args.timeout,
                check=False,
            )
        except subprocess.TimeoutExpired:
            print(f"skip (timeout): {f}", file=sys.stderr)
            continue
        if p.stderr.strip():
            print(f"{f}: {p.stderr.strip()[:200]}", file=sys.stderr)
        for line in p.stdout.splitlines():
            name, digest = line.split()
            table.setdefault(name, set()).add(digest)
    body = "".join(
        f'  ("{n}", [ {"; ".join(chr(34) + d + chr(34) for d in sorted(ds))} ]);\n' for n, ds in sorted(table.items())
    )
    TARGET.write_text(
        "(* Generated by tools/gen_prims.py from official lean4export files; checked by test/test_prim.ml. Do not edit by hand. *)\n"
        f"let table : (string * string list) list = [\n{body}]\n",
        encoding="utf-8",
    )
    print(f"{len(table)} primitives, {sum(len(v) for v in table.values())} digests")


if __name__ == "__main__":
    main()
